"""Contractor demo: a separate demo account whose homes act out common faults.

  python demo.py setup     create the demo account, six homes and a day of history
  python demo.py run       keep the homes live (Ctrl+C to stop)
  python demo.py reset     delete everything the demo created (the rest of the database is untouched)

Sign in with the demo contractor account to show the fleet page, alerts, the technician view,
equipment and service history; the Garcia homeowner account shows the homeowner page. The
passwords are generated by `setup` and saved in demo-login.txt (git-ignored).

Readings go straight through the ingest code (no MQTT or nodes needed) into whichever database
DATABASE_URL points at. Demo systems never send alert email.
"""
