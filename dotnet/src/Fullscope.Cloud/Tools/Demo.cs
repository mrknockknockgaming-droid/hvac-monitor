/// <summary>
/// Contractor demo (demo.py): a separate demo account whose homes act out common faults.
///
///   fullscope demo setup     create the demo account, seven homes and a day of history
///   fullscope demo run       keep the homes live (Ctrl+C to stop)
///   fullscope demo reset     delete everything the demo created (the rest of the database is untouched)
///
/// Sign in with the demo contractor account to show the fleet page, alerts, the technician view,
/// equipment and service history; the Garcia homeowner account shows the homeowner page. The
/// passwords are generated by `setup` and saved in demo-login.txt (git-ignored).
///
/// Two homes have a display thermostat and an electrical module: Garcia (healthy) and Rivera, whose
/// compressor run capacitor started reading weak 2.5 hours before setup.
///
/// Readings go straight through the ingest code (no MQTT or nodes needed) into whichever database
/// DATABASE_URL points at. Demo systems never send alert email.
/// </summary>
public sealed class Demo
{
