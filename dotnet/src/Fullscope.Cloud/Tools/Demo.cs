    public string LoginFile { get; }

    /// <param name="wallClock">Real time, for the offline home (tests pass a fixed one).</param>
    public Demo(DbFactory sessions, Settings settings, Random? random = null, Func<double>? wallClock = null)
    {
        _sessions = sessions;
        _settings = settings;
        _rnd = random ?? Random.Shared;
        _wallClock = wallClock ?? Time.Now;
        LoginFile = Path.Combine(settings.Home, "demo-login.txt");
    }

    double J3(double x) => x + _rnd.NextDouble() * 0.6 - 0.3;

    /// <summary>Arizona summer day: ~84 F before dawn to ~108 F mid-afternoon (local time).</summary>
    static double OutdoorTemp(double t)
    {
        var local = TimeZoneInfo.ConvertTimeFromUtc(Time.FromEpoch(Math.Floor(t)), Time.LocalZone);
        double hour = local.Hour + local.Minute / 60.0;
        return 96 + 12 * Math.Sin((hour - 9.5) / 24 * 2 * Math.PI);
    }

    static bool Running(Home home, double t, int index)
    {
        if (home.On is not int on) return true;
        double period = (on + home.Off!.Value) * 60;
        return Py.Mod(t + index * 437, period) < on * 60;
    }

    /// <summary>A home with a Fullscope thermostat: the controller runs a simple house whose
    /// temperature drifts toward outdoors and is pulled down while the compressor runs.</summary>
    sealed class DemoThermostat
    {
        readonly ThermostatController _ctrl = new(TstatSettings(), TstatTech());
        double? _onSince;
        double _last;
        public double Room;

        public DemoThermostat(double t)
        {
            var (_, cool, _, _) = Thermostat.ScheduleNow(TstatSettings(), Thermostat.LocalNow(TstatTech(), t));
            Room = Py.NumberOf(cool)!.Value.V + 1.5;          // warm enough to be cooling at the start
            _last = t;
        }

        public (JsonObject Rep, bool On, double Warm) Step(double t, double oat)
        {
            var rep = _ctrl.Step(Num.Float(Py.Round(Room, 2)), oat, t, Thermostat.LocalNow(TstatTech(), t));
            bool on = J.Truthy(rep["out"], "Y");
            _onSince = on ? _onSince ?? t : null;
            double warm = on ? Math.Min(1.0, (t - _onSince!.Value) / 240) : 0.0;
            double dtS = Math.Max(0.0, Math.Min(t - _last, 600));
            Room += dtS * (oat - Room) / (5 * 3600) - (on ? dtS * 0.35 / 60 * warm : 0);
            _last = t;
            rep["node"] = "thermostat";
            rep["fw"] = "demo";
            rep["uptime"] = (long)Py.Mod(Math.Floor(t), 864000);
            rep["cfg_ver"] = 1;
            rep["err"] = new JsonArray();
            rep["room"]!["rh"] = 38.0;
            return (rep, on, warm);
        }
    }

    string ElectricalFault(Home home, double t) => t >= _faultStart.GetValueOrDefault(home.Site, 0) ? home.Electrical! : "none";

    /// <summary>(outdoor JSON, indoor JSON or null) for a home at time t, as the firmware would send them.</summary>
    (JsonObject Outdoor, JsonObject? Indoor) Readings(Home home, double t, int index, bool? onOverride = null, double? room = null)
    {
        var sc = Scenarios[home.Scenario];
        bool on = onOverride ?? Running(home, t, index);
        double oat = OutdoorTemp(t);
        if (sc.OatCap is double cap) oat = Math.Min(oat, cap);
        double pVap, pLiq, tSuc, tLiq;
        if (on)
        {
            (pVap, pLiq) = (J3(sc.PVap), J3(sc.PLiq + 2 * (oat - 96)));
            double satHigh = _tables.BubbleF("R-410A", pLiq + 14.0)!.Value;
            (tSuc, tLiq) = (J3(sc.TSuc), J3(satHigh - sc.Sc));
        }
        else                                                 // pressures equalise, lines drift to ambient
        {
            pVap = pLiq = J3(240 + oat);
            (tSuc, tLiq) = (J3(oat - 4), J3(oat - 1));
        }
        long uptime = (long)Py.Mod(Math.Floor(t), 864000);
        static JsonNode R(double x) => JsonValue.Create(Py.Round(x, 1));
        var outdoor = new JsonObject
        {
            ["node"] = "outdoor", ["fw"] = "demo", ["rssi"] = -60, ["uptime"] = uptime,
            ["mode"] = new JsonObject { ["Y"] = on, ["OB"] = on },
            ["p"] = new JsonObject { ["liq"] = R(pLiq), ["vap"] = R(pVap), ["tsuc"] = null },
            ["t"] = new JsonObject { ["suc"] = R(tSuc), ["liq"] = R(tLiq), ["tsuc"] = null, ["dis"] = null },
            ["air"] = new JsonObject { ["t"] = R(J3(oat)), ["rh"] = 14.0 }, ["v5"] = 5.02, ["err"] = new JsonArray(),
        };
        if (home.Scenario == "monitor_offline" && t > _wallClock() - OfflineSinceH * 3600) return (outdoor, null);
        double ret = room is double rm ? J3(rm) : J3(77.0);
        double supply = on ? ret - sc.Dt : ret - 1;
        var indoor = new JsonObject
        {
            ["node"] = "indoor", ["fw"] = "demo", ["rssi"] = -55, ["uptime"] = uptime,
            ["mode"] = new JsonObject { ["Y"] = on, ["W"] = false, ["G"] = on, ["OB"] = on },
            ["air"] = new JsonObject { ["supply"] = R(J3(supply)), ["return"] = R(ret), ["dt"] = null }, ["err"] = new JsonArray(),
        };
        return (outdoor, indoor);
    }

    void Feed(Ingest.Ingest ingest, double t)
    {
        for (int index = 0; index < Homes.Length; index++)
        {
            var home = Homes[index];
            bool? on = null;
            double? room = null;
            double warm = 0;
            if (home.Thermostat)
            {
                if (!_tstats.TryGetValue(home.Site, out var ts)) _tstats[home.Site] = ts = new DemoThermostat(t);
                (var rep, bool o, warm) = ts.Step(t, OutdoorTemp(t));
                (on, room) = (o, ts.Room);
                ingest.Handle($"hvac/{home.Site}/thermostat/telemetry", Py.Dumps(rep), t - 0.6);
            }
            if (home.Electrical is not null)
            {
                var elec = Simulator.Electrical(t / 60, on ?? false, warm, ElectricalFault(home, t));
                ingest.Handle($"hvac/{home.Site}/electrical/telemetry", Py.Dumps(elec), t - 0.3);
            }
            var (outdoor, indoor) = Readings(home, t, index, on, room);
            if (indoor is not null) ingest.Handle($"hvac/{home.Site}/indoor/telemetry", Py.Dumps(indoor), t);
            ingest.Handle($"hvac/{home.Site}/outdoor/telemetry", Py.Dumps(outdoor), t + 1);
        }
    }

    static Account? DemoAccount(Db s) => s.Accounts.FirstOrDefault(a => a.Email == AccountEmail && a.Name == AccountName);

    public sealed class DemoExit(string message) : Exception(message);

    public void Setup(int backfillHours = 24, Action<string>? say = null)
    {
        say ??= Console.WriteLine;
        var today = Time.Today();
        string techPw = Db.TokenUrlSafe(9), ownerPw = Db.TokenUrlSafe(9);
        int acctId;
        using (var s = _sessions.Open())
        using (var tx = s.Database.BeginTransaction())
        {
            if (DemoAccount(s) is not null) throw new DemoExit("The demo already exists. Run `fullscope demo reset` first to start over.");
            if (s.Users.Any(u => u.Email == TechLogin || u.Email == HomeownerLogin))
                throw new DemoExit($"{TechLogin} or {HomeownerLogin} already has a sign-in; remove it first.");
            var acct = new Account { Name = AccountName, Email = AccountEmail };
            s.Accounts.Add(acct);
            s.SaveChanges();
            s.Users.Add(new User { Email = TechLogin, Name = "Demo technician", Role = "contractor", AccountId = acct.Id, PasswordHash = Passwords.Hash(techPw) });
            for (int i = 0; i < Homes.Length; i++)
            {
                var home = Homes[i];
                if (s.Systems.Any(x => x.SiteId == home.Site)) throw new DemoExit($"site {home.Site} is already used");
                var sy = new HvacSystem { AccountId = acct.Id, Name = home.Name, SiteId = home.Site, Refrigerant = "R-410A", HeatPump = true, ObEnergized = "cool", AtmPsia = 14.0 };
                s.Systems.Add(sy);
                s.SaveChanges();
                var eq = new EquipmentRow { SystemId = sy.Id, SystemType = "split_hp", Metering = "txv", Tonnage = home.Tons, ScTarget = 10.0, ScTolerance = 4.0, ElevationFt = 1240 };
                if (home.Electrical is not null) (eq.CompRla, eq.CompLra, eq.FanFla, eq.CapHermUf, eq.CapFanUf) = (14.1, 73.0, 1.4, 45.0, 5.0);
                s.Equipment.Add(eq);
                if (home.Thermostat)
                    s.ThermostatConfigs.Add(new ThermostatConfig { SystemId = sy.Id, Settings = Db.Json(TstatSettings())!, Tech = Db.Json(TstatTech())!, Version = 1, Sent = true, UpdatedAt = Db.UtcNow() });
                s.ServiceInfo.Add(new ServiceInfo { SystemId = sy.Id, Name = ContractorName, Phone = ContractorPhone, Email = ContractorEmail });
                s.AlertPrefs.Add(new AlertPrefs { SystemId = sy.Id, EmailOwner = false, EmailContractor = false });   // demo never emails
                s.MaintenanceItems.Add(new MaintenanceItem { SystemId = sy.Id, Kind = "filter", IntervalDays = 90, IntervalRunHours = 500.0, LastDone = today.AddDays(-home.FilterDays) });
                s.MaintenanceItems.Add(new MaintenanceItem { SystemId = sy.Id, Kind = "tuneup", IntervalDays = 182, LastDone = today.AddDays(-(40 + 25 * i)) });
                double hours = home.Scenario == "dirty_filter" ? 10.0 : 6.0;       // only Thompson's filter is overdue
                for (int d = 0; d < Math.Min(home.FilterDays, 120); d++)
                    s.RuntimeDays.Add(new RuntimeDay { SystemId = sy.Id, Day = today.AddDays(-d), BlowerS = hours * 3600, CompressorS = (hours - 1) * 3600 });
                s.ServiceVisits.Add(new ServiceVisit
                {
                    SystemId = sy.Id, Date = today.AddDays(-(40 + 25 * i)), Kind = "tuneup", Technician = "Demo technician",
                    Work = "Spring tune-up: cleaned condenser coil, checked charge and capacitor, tightened electrical connections.", FilterChanged = false,
                });
                if (home.Scenario == "low_charge")
                    s.ServiceVisits.Add(new ServiceVisit { SystemId = sy.Id, Date = today.AddDays(-400), Kind = "repair", Technician = "Demo technician", Work = "Added 1.5 lb R-410A; recommended a leak search." });
                if (home.Site == "demo-garcia")
                {
                    var owner = new User { Email = HomeownerLogin, Name = "Maria Garcia", Role = "homeowner", PasswordHash = Passwords.Hash(ownerPw) };
                    s.Users.Add(owner);
                    s.SaveChanges();
                    s.SystemMembers.Add(new SystemMember { SystemId = sy.Id, UserId = owner.Id });
                }
                s.SaveChanges();
            }
            tx.Commit();
            acctId = acct.Id;
        }
        File.WriteAllText(LoginFile, "Fullscope demo sign-ins (made by fullscope demo setup; local only, not committed)\n\n" +
                                     $"Contractor:  {TechLogin}  /  {techPw}\nHomeowner:   {HomeownerLogin}  /  {ownerPw}\n");

        say($"Demo account {acctId} created with {Homes.Length} homes. Backfilling {backfillHours} h of readings...");
        // readings a minute apart: tell the ingest so it doesn't take each gap for an outage
        var ingest = new Ingest.Ingest(_sessions, _tables, stale: 2 * BackfillStepS);
        double now = _wallClock(), t0 = now - backfillHours * 3600;
        _tstats.Clear();
        foreach (var h in Homes.Where(h => h.Electrical is not null and not "none")) _faultStart[h.Site] = now - FaultSinceH * 3600;
        int steps = backfillHours * 3600 / BackfillStepS;
        for (int k = 0; k < steps; k++)
        {
            Feed(ingest, t0 + k * BackfillStepS);
            if (k % 240 == 0) say($"  {100 * k / steps} %");
        }
        PastAlerts(acctId);
        say($"Done. Sign-ins saved in {LoginFile}. Keep it live with `fullscope demo run`.");
    }

    /// <summary>A little history for the alert logs: problems that came and went earlier in the week.</summary>
    void PastAlerts(int acctId)
    {
        var now = Db.UtcNow();
        DateTime Ago(double days, double hours = 0) => now - TimeSpan.FromDays(days) - TimeSpan.FromHours(hours);
        var history = new Dictionary<string, (string Code, string Level, string Text, DateTime Start, int Minutes)[]>
        {
            ["demo-garcia"] = [("dt_low", "warn", "Air delta-T 11.2°F is low", Ago(4, 3), 45)],
            ["demo-miller"] = [("no_data", "warn", "No readings from either node for 10 min", Ago(2, 5), 70)],
            ["demo-brooks"] = [("sh_low", "alert", "Superheat 2.4°F: risk of liquid floodback", Ago(6, 2), 30)],
        };
        using var s = _sessions.Open();
        foreach (var sy in s.Systems.Where(x => x.AccountId == acctId).ToList())
            foreach (var (code, level, text, start, minutes) in history.GetValueOrDefault(sy.SiteId, []))
            {
                var end = start.AddMinutes(minutes);
                s.Alerts.Add(new Alert
                {
                    SystemId = sy.Id, Code = code, Level = level, Text = text, StartedAt = start, LastSeen = end,
                    RaisedAt = start.AddMinutes(5), ClearedAt = end.AddMinutes(5),
                });
            }
        s.SaveChanges();
    }

    /// <summary>When each home's electrical fault began: from its alert if raised, else now.</summary>
    void FaultStarts()
    {
        using var s = _sessions.Open();
        foreach (var h in Homes.Where(h => h.Electrical is not null and not "none"))
        {
            int? sid = s.Systems.Where(x => x.SiteId == h.Site).Select(x => (int?)x.Id).FirstOrDefault();
            var first = s.Alerts.Where(a => a.SystemId == sid && a.Code == "cap_herm").OrderBy(a => a.StartedAt).Select(a => (DateTime?)a.StartedAt).FirstOrDefault();
            _faultStart[h.Site] = first is DateTime f ? Db.Epoch(f) : _wallClock();
        }
    }

    /// <summary>Fill the gap since the demo last ran (up to a day), so the homes look like they kept
    /// running instead of coming back from an outage (which restarts run timers and closes alerts).</summary>
    void CatchUp(Ingest.Ingest ingest, Action<string> say)
    {
        DateTime? last;
        using (var s = _sessions.Open())
        {
            var acct = DemoAccount(s)!;
            var ids = s.Systems.Where(x => x.AccountId == acct.Id).Select(x => x.Id).ToList();
            last = s.Snapshots.Where(x => ids.Contains(x.SystemId)).OrderByDescending(x => x.Time).Select(x => (DateTime?)x.Time).FirstOrDefault();
        }
        double now = _wallClock();
        double start = Math.Max(now - 24 * 3600, last is DateTime l ? Db.Epoch(l) : now - 24 * 3600);
        if (now - start < 2 * StepS) return;
        say($"Catching up {Math.Round((now - start) / 60)} min since the demo last ran...");
        ingest.Stale = 2 * BackfillStepS;
        for (double t = start + BackfillStepS; t < now; t += BackfillStepS) Feed(ingest, t);
        Feed(ingest, _wallClock() - 2);
        ingest.Stale = _settings.StaleSeconds;
    }

    public void Run(CancellationToken stop, Action<string>? say = null)
    {
        say ??= Console.WriteLine;
        using (var s = _sessions.Open())
            if (DemoAccount(s) is null) throw new DemoExit("No demo yet: run `fullscope demo setup` first.");
        var ingest = new Ingest.Ingest(_sessions, _tables, _settings);
        FaultStarts();
        CatchUp(ingest, say);
        say($"Demo running: {Homes.Length} homes, a reading every {StepS} s (Ctrl+C to stop).");
        double lastSweep = 0;
        while (!stop.IsCancellationRequested)
        {
            double now = _wallClock();
            Feed(ingest, now);
            if (now - lastSweep >= 60)
            {
                ingest.Sweep(now);
                lastSweep = now;
            }
            try { Task.Delay(TimeSpan.FromSeconds(Math.Max(0.5, StepS - (_wallClock() - now))), stop).Wait(stop); }
            catch (OperationCanceledException) { break; }
        }
        say("stopped");
    }

    /// <summary>Delete the demo account and everything that belongs to it, and nothing else.</summary>
    public void Reset(Action<string>? say = null)
    {
        say ??= Console.WriteLine;
        int homes;
        using (var s = _sessions.Open())
        using (var tx = s.Database.BeginTransaction())
        {
            var acct = DemoAccount(s);
            if (acct is null)
            {
                say("No demo account found; nothing to delete.");
                return;
            }
            var sys = s.Systems.Where(x => x.AccountId == acct.Id).Select(x => x.Id).ToList();
            var devs = s.Devices.Where(d => sys.Contains(d.SystemId)).Select(d => d.Id).ToList();
            var users = s.Users.Where(u => u.AccountId == acct.Id).Select(u => u.Id).ToList();
            users.AddRange(s.SystemMembers.Where(m => sys.Contains(m.SystemId)).Select(m => m.UserId).ToList());
            s.Telemetry.Where(x => devs.Contains(x.DeviceId)).ExecuteDelete();
            s.Commands.Where(x => devs.Contains(x.DeviceId)).ExecuteDelete();
            s.Snapshots.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.SnapshotMinutes.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.Alerts.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.AlertMutes.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.AlertPrefs.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.Equipment.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.ServiceInfo.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.MaintenanceItems.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.RuntimeDays.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.ServiceVisits.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.SystemMembers.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.ThermostatConfigs.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.Devices.Where(x => sys.Contains(x.SystemId)).ExecuteDelete();
            s.Invites.Where(x => (x.SystemId != null && sys.Contains(x.SystemId.Value)) || x.AccountId == acct.Id).ExecuteDelete();
            s.UserSessions.Where(x => users.Contains(x.UserId)).ExecuteDelete();
            s.PasswordResets.Where(x => users.Contains(x.UserId)).ExecuteDelete();
            s.Users.Where(x => users.Contains(x.Id) && x.Email.EndsWith("@fullscope.example")).ExecuteDelete();
            s.ApiKeys.Where(x => x.AccountId == acct.Id).ExecuteDelete();
            s.Systems.Where(x => sys.Contains(x.Id)).ExecuteDelete();
            s.Accounts.Where(x => x.Id == acct.Id).ExecuteDelete();
            tx.Commit();
            homes = sys.Count;
        }
        if (File.Exists(LoginFile)) File.Delete(LoginFile);
        say($"Demo removed ({homes} homes).");
    }

    public static int Command(Settings settings, string[] args, ILoggerFactory logs, CancellationToken stop)
    {
        var cmd = args.FirstOrDefault();
        if (cmd is not ("setup" or "run" or "reset"))
        {
            Console.Error.WriteLine("usage: fullscope demo setup | run | reset");
            return 2;
        }
        var demo = new Demo(DbFactory.FromUrl(settings.DatabaseUrl).Init(settings.KeepDays), settings);
        try
        {
            if (cmd == "setup") demo.Setup();
            else if (cmd == "run") demo.Run(stop);
            else demo.Reset();
            return 0;
        }
        catch (DemoExit e)
        {
            Console.Error.WriteLine(e.Message);
            return 1;
        }
    }
